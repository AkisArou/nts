#!/usr/bin/env node
// Diagnose the available compiler; resolved failures remain useful controls.
import assert from "node:assert/strict";
import { execFileSync, spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "../../../..");
const fixture = import.meta.dirname;
const output = resolve(root, "target/chromium/contracts");
const nts = resolve(root, process.env.NTS_BIN ?? "target/release/nts");
const source = resolve(root, "third_party/chromium/src");
const clang = resolve(source, "third_party/llvm-build/Release+Asserts/bin/clang");
const sysroot = resolve(source, "build/linux/debian_bullseye_amd64-sysroot");
const hash = (path: string): string => createHash("sha256").update(readFileSync(path)).digest("hex");
const compilerSha256 = hash(nts);
mkdirSync(output, { recursive: true });
const runId = new Date().toISOString().replaceAll(/[:.]/g, "-");
const runOutput = resolve(output, runId);
mkdirSync(runOutput);

function emit(project: string, directory: string, backend: "c" | "llvm", name: string) {
  // emit-llvm is a stdout diagnostic command. Generate the corresponding C
  // header/runtime first, then replace only the program object with LLVM.
  let preparation = "";
  if (backend === "llvm") {
    const c = spawnSync(nts, ["emit-c", project, "--out", directory, "--rc"], {
      cwd: root, encoding: "utf8", maxBuffer: 32 * 1024 * 1024, timeout: 120_000,
      env: { ...process.env, NTS_NO_ACQUIRE: "1" },
    });
    if (c.error) throw c.error;
    preparation = `${c.stdout}${c.stderr}`;
  }
  const result = spawnSync(nts, [`emit-${backend}`, project, "--out", directory, "--rc"], {
    cwd: root, encoding: "utf8", maxBuffer: 32 * 1024 * 1024, timeout: 120_000,
    env: { ...process.env, NTS_NO_ACQUIRE: "1" },
  });
  if (result.error) throw result.error;
  const programPath = resolve(directory, backend === "c" ? "program.c" : "program.ll");
  if (backend === "llvm" && result.stdout.includes("; Generated by nts.")) writeFileSync(programPath, result.stdout);
  const log = preparation + (backend === "llvm" && result.stdout.includes("; Generated by nts.") ? result.stderr : `${result.stdout}${result.stderr}`);
  const logPath = resolve(runOutput, `${name}-${backend}.log`);
  writeFileSync(logPath, log);
  const headerPath = resolve(directory, "program.h");
  const header = existsSync(headerPath) ? readFileSync(headerPath, "utf8") : "";
  return { exitCode: result.status, logPath, log, programPath, header, emitted: existsSync(programPath) };
}

const lifetime = [];
for (const backend of ["c", "llvm"] as const) {
  const directory = resolve(runOutput, backend);
  const emission = emit(resolve(fixture, "tsconfig.json"), directory, backend, "lifetime");
  assert.equal(emission.exitCode, 0, emission.log);
  for (const symbol of ["createCounter", "managedAwait", "literalUnit"]) assert(emission.header.includes(`${symbol}(`), `${backend}: missing ${symbol}`);
  const program = resolve(directory, "program.o");
  execFileSync(clang, [...(backend === "c" ? [`--sysroot=${sysroot}`, "-std=c11", "-DNTS_PROVIDER_RC", "-D_GNU_SOURCE", "-I", directory] : []),
    "-O2", "-c", emission.programPath, "-o", program], { stdio: "inherit" });
  const executable = resolve(directory, "caller");
  execFileSync(clang, [`--sysroot=${sysroot}`, "-std=c11", "-DNTS_PROVIDER_RC", "-D_GNU_SOURCE", "-O2", "-fuse-ld=lld", "-I", directory,
    resolve(fixture, "native/caller.c"), program, resolve(directory, "nts_runtime.c"), "-lm", "-o", executable], { stdio: "inherit" });
  const observed = JSON.parse(execFileSync(executable, [], { encoding: "utf8" })) as { counterSurvived: boolean; liveAfterPromiseRelease: number; literalUnits: number[] };
  const expectedUnits = [65, 0, 233, 937, 55296, 90, 56320, 55357, 56832];
  const code = readFileSync(emission.programPath, "utf8");
  const nullDropWitness = code.split("\n").filter(line => backend === "c" ? line.includes("nts_promise_subscribe(") && line.includes("&managedAwait__resume, 0,") : /store ptr null, ptr .*\.drop/.test(line));
  lifetime.push({ backend, ...observed, expectedUnits, literalPreserved: JSON.stringify(observed.literalUnits) === JSON.stringify(expectedUnits),
    nullDropWitness, logPath: emission.logPath, programSha256: hash(emission.programPath), runtimeSha256: hash(resolve(directory, "nts_runtime.c")) });
  console.log(`${backend}: managed argument survives=${observed.counterSurvived}; lone-surrogate literal preserved=${JSON.stringify(observed.literalUnits) === JSON.stringify(expectedUnits)}; null await drops=${nullDropWitness.length}`);
}
const admissions = [];
for (const [name, project, symbol] of [
  ["managed-opaque", resolve(fixture, "managed-opaque/tsconfig.json"), "managedOpaque"],
]) {
  for (const backend of ["c", "llvm"] as const) {
    const emission = emit(project, resolve(runOutput, `${name}-${backend}`), backend, name);
    const hasDefinition = emission.emitted && (backend === "c" || new RegExp(`define[^\\n]+@${symbol}\\(`).test(readFileSync(emission.programPath, "utf8")));
    const admitted = emission.exitCode === 0 && hasDefinition && emission.header.includes(`${symbol}(`);
    admissions.push({ name, backend, admitted, exitCode: emission.exitCode, emitted: emission.emitted, logPath: emission.logPath,
      diagnostics: emission.log.split("\n").filter(line => /invalid HIR:|Error:|NTS\d{4}|refus|unsupported/.test(line)) });
    console.log(`${name}/${backend}: ${admitted ? "admitted" : "blocked"}; evidence ${emission.logPath}`);
  }
}
assert.equal(hash(nts), compilerSha256, "compiler changed during the diagnostic run");
const result = {
  observedAt: new Date().toISOString(), repositoryHeadAtCheck: execFileSync("git", ["rev-parse", "HEAD"], { cwd: root, encoding: "utf8" }).trim(),
  compiler: { path: nts, sha256: compilerSha256, mtime: statSync(nts).mtime.toISOString() },
  scope: "Compiler admission and standalone lifetime diagnostics; no Chromium acceptance.",
  inputs: Object.fromEntries(["src/main.ts", "native/caller.c", "managed-opaque/main.ts", "managed-opaque/host.d.ts"].map(path => [path, hash(resolve(fixture, path))])),
  lifetime, admissions,
};
writeFileSync(resolve(output, "result.json"), `${JSON.stringify(result, null, 2)}\n`);
console.log(`Diagnostics recorded: ${resolve(output, "result.json")}`);
