//! Writing the vendor tree, the generated config, and the lock.
//!
//! # What this is allowed to touch
//!
//! `<project>/.nts/` and `<project>/tsconfig.nts.json`, and nothing else. The
//! developer's `tsconfig.json`, `package.json` and `node_modules` are read and
//! never written, because `nts check` compares a compiled program against node
//! running the same TypeScript — which only works while the program still
//! resolves its dependencies the ordinary way. Rewriting the project's own
//! resolution would break the oracle, and the editor with it.

use std::collections::BTreeMap;

use camino::{Utf8Path, Utf8PathBuf};
use serde::{Deserialize, Serialize};

use crate::recover::RecoveredFile;

/// What one acquisition wrote, so the next one can skip it.
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct Lock {
    /// Bumped when the layout this crate writes changes shape.
    pub version: u32,
    pub packages: BTreeMap<String, LockedPackage>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct LockedPackage {
    pub version: String,
    /// Where it was read from, after symlinks. Part of the identity: the same
    /// version resolved from a different store is a different input.
    pub source: String,
    pub route: String,
    /// Digest of the recovered text. This is the *source* identity, and it is
    /// recorded separately from the package version on purpose — a version
    /// pins a tarball, and what was compiled came out of a source map inside
    /// it.
    pub digest: String,
    pub files: usize,
    /// Specifier -> the vendor-relative file it resolves to.
    ///
    /// Recorded so a settled run can rebuild the `paths` without recovering
    /// anything. Recovery means indexing every source map in a package, which
    /// on a large closure is most of what a no-op acquisition costs.
    #[serde(default)]
    pub mapped: BTreeMap<String, String>,
}

pub const LOCK_VERSION: u32 = 1;

/// Write a package's recovered files under the vendor root.
///
/// Returns how many files were actually written: an unchanged file is left
/// alone so that build systems watching mtimes do not see churn on every run.
pub fn write_package(
    vendor_root: &Utf8Path,
    package: &str,
    files: &[RecoveredFile],
) -> Result<usize, EmitError> {
    let root = vendor_root.join(package_dir(package));
    let mut written = 0;
    for file in files {
        let at = root.join(&file.at);
        if std::fs::read_to_string(&at).is_ok_and(|existing| existing == file.text) {
            continue;
        }
        if let Some(parent) = at.parent() {
            std::fs::create_dir_all(parent).map_err(|source| EmitError::Write {
                path: parent.to_owned(),
                source,
            })?;
        }
        std::fs::write(&at, &file.text).map_err(|source| EmitError::Write {
            path: at.clone(),
            source,
        })?;
        written += 1;
    }
    Ok(written)
}

/// A scoped name is a directory, not two.
///
/// `@scope/name` becomes `@scope__name`, which keeps one package to one
/// directory and keeps a package called `@a/b` from colliding with a directory
/// another package legitimately owns.
#[must_use]
pub fn package_dir(name: &str) -> String {
    name.replace('/', "__")
}

#[must_use]
pub fn digest(files: &[RecoveredFile]) -> String {
    let mut hasher = xxhash_rust::xxh3::Xxh3::new();
    for file in files {
        hasher.update(file.at.as_str().as_bytes());
        hasher.update(b"\0");
        hasher.update(file.text.as_bytes());
        hasher.update(b"\0");
    }
    format!("{:016x}", hasher.digest())
}

/// The config the compiler is pointed at.
///
/// It extends the project's own and adds `paths`. It deliberately does *not*
/// restate `include`: TypeScript pulls in any file reachable by import from a
/// root file whether or not `include` mentions it, which is what makes the
/// vendored tree part of the program without the generated config having to
/// reproduce the project's file selection.
pub fn write_tsconfig(
    project: &Utf8Path,
    extends: &str,
    root_dir: &str,
    paths: &BTreeMap<String, Vec<String>>,
    inherited: &BTreeMap<String, Vec<String>>,
) -> Result<Utf8PathBuf, EmitError> {
    let mut merged: BTreeMap<String, Vec<String>> = inherited.clone();
    for (specifier, targets) in paths {
        // The project wins: a developer who mapped a specifier by hand meant it.
        merged.entry(specifier.clone()).or_insert_with(|| targets.clone());
    }

    let document = serde_json::json!({
        "//": "Generated by `nts deps`. Not edited by hand; not the project's own \
               tsconfig, which is left alone so the program still runs under node.",
        "extends": extends,
        "compilerOptions": {
            // The program's root is the *workspace*, not this package. Both
            // things a dependency can be — a vendored source tree and a
            // sibling package — live above the importing package, and a
            // `rootDir` that does not contain them is refused with TS6059
            // before the compiler ever sees the program.
            "rootDir": root_dir,
            // A *composite* project must list every one of its files, so a
            // dependency reached only by an import is rejected with TS6307 —
            // which is how a project that inherits `composite: true` from a
            // shared base fails the moment its dependencies are acquired. This
            // config is not a project-reference target and never emits, so the
            // whole emit group is switched off together, the way
            // `runtime/node/tsconfig.module.json` already does it for the same
            // reason. `emitDeclarationOnly` has to go with `noEmit`: the two
            // cannot both be set.
            "composite": false,
            "declaration": false,
            "declarationMap": false,
            "emitDeclarationOnly": false,
            "incremental": false,
            "noEmit": true,
            // No `baseUrl`: TypeScript 7 removed it, and without one `paths`
            // resolve relative to the config file that declares them — which is
            // this file, sitting in the project directory. That is the same
            // coordinate system the targets are written in.
            "paths": merged,
        },
    });

    let at = project.join("tsconfig.nts.json");
    let text = format!(
        "{}\n",
        serde_json::to_string_pretty(&document).map_err(EmitError::Encode)?
    );
    if std::fs::read_to_string(&at).is_ok_and(|existing| existing == text) {
        return Ok(at);
    }
    std::fs::write(&at, text).map_err(|source| EmitError::Write {
        path: at.clone(),
        source,
    })?;
    Ok(at)
}

#[must_use]
pub fn read_lock(project: &Utf8Path) -> Lock {
    std::fs::read_to_string(lock_path(project))
        .ok()
        .and_then(|text| serde_json::from_str::<Lock>(&text).ok())
        .filter(|lock| lock.version == LOCK_VERSION)
        .unwrap_or_default()
}

pub fn write_lock(project: &Utf8Path, lock: &Lock) -> Result<(), EmitError> {
    let at = lock_path(project);
    if let Some(parent) = at.parent() {
        std::fs::create_dir_all(parent).map_err(|source| EmitError::Write {
            path: parent.to_owned(),
            source,
        })?;
    }
    let text = format!(
        "{}\n",
        serde_json::to_string_pretty(lock).map_err(EmitError::Encode)?
    );
    if std::fs::read_to_string(&at).is_ok_and(|existing| existing == text) {
        return Ok(());
    }
    std::fs::write(&at, text).map_err(|source| EmitError::Write { path: at, source })
}

#[must_use]
pub fn lock_path(project: &Utf8Path) -> Utf8PathBuf {
    project.join(".nts").join("deps.lock")
}

/// Remove vendored packages that are no longer in the closure.
///
/// A dependency that was uninstalled leaves source behind, and stale source
/// that still resolves is worse than none: the program would compile against a
/// package the developer removed.
#[must_use]
pub fn prune(vendor_root: &Utf8Path, keep: &[String]) -> Vec<String> {
    let keep: Vec<String> = keep.iter().map(|name| package_dir(name)).collect();
    let Ok(entries) = std::fs::read_dir(vendor_root) else {
        return Vec::new();
    };
    let mut removed = Vec::new();
    for entry in entries.flatten() {
        let Ok(name) = entry.file_name().into_string() else {
            continue;
        };
        if keep.contains(&name) {
            continue;
        }
        if std::fs::remove_dir_all(entry.path()).is_ok() {
            removed.push(name.replace("__", "/"));
        }
    }
    removed.sort();
    removed
}

#[derive(Debug, thiserror::Error)]
pub enum EmitError {
    #[error("could not write `{path}`: {source}")]
    Write {
        path: Utf8PathBuf,
        #[source]
        source: std::io::Error,
    },
    #[error("could not encode JSON: {0}")]
    Encode(#[source] serde_json::Error),
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_scoped_name_is_one_directory() {
        assert_eq!(package_dir("@isaacs/fs-minipass"), "@isaacs__fs-minipass");
        assert_eq!(package_dir("mitt"), "mitt");
    }

    #[test]
    fn the_digest_follows_content_and_path() {
        let one = [RecoveredFile {
            at: "a.ts".into(),
            text: "x".to_owned(),
        }];
        let moved = [RecoveredFile {
            at: "b.ts".into(),
            text: "x".to_owned(),
        }];
        let changed = [RecoveredFile {
            at: "a.ts".into(),
            text: "y".to_owned(),
        }];
        assert_ne!(digest(&one), digest(&moved));
        assert_ne!(digest(&one), digest(&changed));
        assert_eq!(digest(&one), digest(&one.clone()));
    }
}
