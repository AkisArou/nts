//! Native string hashing, shared by literal emission and the generated C runtime.
//!
//! Hash UTF-16 code units, independent of the narrow/wide storage chosen by an
//! emitter. The operation lists below also generate the runtime's C primitives;
//! the tests reject a stale generated block and execute both C storage widths.
use std::fmt::Write;

/// A literal has a settled hash, even though its storage cannot be written.
/// The C emitter asserts agreement with `NTS_HASHED` in the runtime header.
pub const HASHED: u32 = 0x80;

const SEED: u64 = 0xcbf2_9ce4_8422_2325;

#[derive(Clone, Copy, Debug)]
enum Op {
    XorUnit,
    Multiply(u64),
    XorShift(u32),
}

const STEP: &[Op] = &[Op::XorUnit, Op::Multiply(0x0100_0000_01b3)];
const MIX: &[Op] = &[
    Op::XorShift(33),
    Op::Multiply(0xff51_afd7_ed55_8ccd),
    Op::XorShift(33),
    Op::Multiply(0xc4ce_b9fe_1a85_ec53),
    Op::XorShift(33),
];

fn apply(mut hash: u64, unit: u16, ops: &[Op]) -> u64 {
    for op in ops {
        hash = match *op {
            Op::XorUnit => hash ^ u64::from(unit),
            Op::Multiply(value) => hash.wrapping_mul(value),
            Op::XorShift(bits) => hash ^ (hash >> bits),
        };
    }
    hash
}

/// The runtime's string-key hash, including the empty string and lone surrogates.
#[must_use]
#[expect(
    clippy::cast_possible_truncation,
    reason = "the hash is the low 32 bits"
)]
pub fn hash_units(units: &[u16]) -> u32 {
    let hash = units
        .iter()
        .fold(SEED, |hash, &unit| apply(hash, unit, STEP));
    apply(hash, 0, MIX) as u32
}

/// Delimiters used by the generator and its synchronization test.
pub const BEGIN: &str = "/* BEGIN GENERATED NATIVE STRING HASH */";
pub const END: &str = "/* END GENERATED NATIVE STRING HASH */";

fn emit_ops(out: &mut String, ops: &[Op], indent: &str) {
    for op in ops {
        let _ = match op {
            Op::XorUnit => writeln!(out, "{indent}h ^= (uint64_t)units[i];"),
            Op::Multiply(value) => writeln!(out, "{indent}h *= 0x{value:016x}ULL;"),
            Op::XorShift(bits) => writeln!(out, "{indent}h ^= h >> {bits};"),
        };
    }
}

/// Generate the private C primitives embedded in `nts_runtime.c`.
///
/// Run `cargo run -p nts-codegen-common --example string-hash-runtime` to update
/// the marked block after changing this module's algorithm.
#[must_use]
pub fn runtime_source() -> String {
    let mut out = format!(
        "{BEGIN}\n\
         /* Generated by compiler/codegen/common/src/string_hash.rs.\n\
         \x20* Regenerate: cargo run -p nts-codegen-common --example string-hash-runtime\n\
         \x20* Hash UTF-16 units; the low 32 bits of a 64-bit avalanche.\n\
         \x20* Narrow and wide strings with the same text are === (nts_string_eq), so\n\
         \x20* they must hash alike. Hashing units, not bytes, guarantees this.\n\
         \x20* Also used for numeric/reference key mixing: keep that contract. */\n\
         static uint32_t nts_hash_mix(uint64_t h) {{\n"
    );
    emit_ops(&mut out, MIX, "  ");
    out.push_str("  return (uint32_t)h;\n}\n");
    for (name, element) in [("narrow", "unsigned char"), ("wide", "uint16_t")] {
        let params = if name == "narrow" {
            format!("const {element} *units,\n{}uint32_t length", " ".repeat(38))
        } else {
            format!("const {element} *units, uint32_t length")
        };
        let indent = "  ";
        let _ = write!(
            out,
            "\nstatic uint32_t nts_hash_{name}_units({params}) {{\n\
             {indent}uint64_t h = 0x{SEED:016x}ULL;\n\
             {indent}for (uint32_t i = 0; i < length; i++) {{\n",
        );
        emit_ops(&mut out, STEP, "    ");
        out.push_str("  }\n  return nts_hash_mix(h);\n}\n");
    }
    let _ = writeln!(out, "{END}");
    out
}

#[cfg(test)]
mod tests {
    use super::{BEGIN, END, hash_units, runtime_source};
    use std::{fs, path::PathBuf, process::Command};

    #[test]
    fn runtime_source_is_current() {
        let source = include_str!("../../../../runtime/c/nts_runtime.c");
        let begin = source.find(BEGIN).expect("generated hash block begins");
        let end = source.find(END).expect("generated hash block ends") + END.len();
        assert_eq!(
            &source[begin..=end],
            runtime_source(),
            "run cargo run -p nts-codegen-common --example string-hash-runtime"
        );
    }

    struct ProbeDir(PathBuf);
    impl Drop for ProbeDir {
        fn drop(&mut self) {
            let _ = fs::remove_dir_all(&self.0);
        }
    }

    #[test]
    fn c_and_rust_hash_the_same_utf16_corpus_in_both_widths() {
        let mut corpus: Vec<Vec<u16>> = [
            "",
            "ASCII key",
            "\0a\0",
            "caf\u{e9}",
            "\u{4e16}\u{754c}",
            "\u{1f600}",
        ]
        .into_iter()
        .map(|text| text.encode_utf16().collect())
        .collect();
        corpus.extend([
            vec![0xd800],
            vec![0xdc00],
            vec![0xd800, 0x41, 0xdfff, 0xd83d, 0xde00],
            (0u16..=255).collect(),
            (0u16..=u16::MAX).collect(),
            (0..8192)
                .map(|at| u16::try_from(at % 251).expect("byte"))
                .collect(),
        ]);
        let dir = ProbeDir(
            PathBuf::from(env!("CARGO_MANIFEST_DIR"))
                .join("../../..")
                .join("target")
                .join(format!("string-hash-parity-{}", std::process::id())),
        );
        fs::create_dir_all(&dir.0).expect("create parity probe directory");
        let mut source = format!(
            "#include <stdint.h>\n#include <stdio.h>\n{}\nint main(void) {{\n",
            runtime_source()
        );
        for (index, units) in corpus.iter().enumerate() {
            use std::fmt::Write;
            let data = units
                .iter()
                .map(u16::to_string)
                .collect::<Vec<_>>()
                .join(",");
            let expected = hash_units(units);
            let data = if data.is_empty() { "0" } else { &data };
            let _ = writeln!(source, "static const uint16_t wide{index}[] = {{{data}}};");
            let _ = writeln!(
                source,
                "if (nts_hash_wide_units(wide{index}, {}) != {expected}u) return 1;",
                units.len()
            );
            if units.iter().all(|&unit| unit <= 255) {
                let _ = writeln!(
                    source,
                    "static const unsigned char narrow{index}[] = {{{data}}};"
                );
                let _ = writeln!(
                    source,
                    "if (nts_hash_narrow_units(narrow{index}, {}) != {expected}u) return 2;",
                    units.len()
                );
            }
        }
        source.push_str("return 0;\n}\n");
        let c = dir.0.join("parity.c");
        let bin = dir.0.join("parity");
        fs::write(&c, source).expect("write parity probe");
        let built = Command::new("clang")
            .args(["-std=c11", "-O2", "-Wall", "-Wextra", "-Werror"])
            .arg(&c)
            .arg("-o")
            .arg(&bin)
            .output()
            .expect("clang compiles parity probe");
        assert!(
            built.status.success(),
            "{}",
            String::from_utf8_lossy(&built.stderr)
        );
        let ran = Command::new(&bin).output().expect("run C parity probe");
        assert!(ran.status.success(), "C/Rust hash mismatch: {ran:?}");
    }
}
