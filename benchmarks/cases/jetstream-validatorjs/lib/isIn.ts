import assertString from './util/assertString.ts';
import toString from './util/toString.ts';

function hasArrayTag(value: unknown): value is Record<string, unknown> {
  return Object.prototype.toString.call(value) === '[object Array]';
}

function isIndexable(value: unknown): value is Record<string, unknown> {
  return value !== null && (typeof value === 'object' || typeof value === 'function');
}

export default function isIn(str: string, options?: string | unknown[] | Record<string, unknown>) {
  assertString(str);
  let i;
  if (hasArrayTag(options)) {
    const array: string[] = [];
    if (!isIndexable(array)) {
      throw new TypeError('Expected the freshly allocated array');
    }
    for (i in options) {
      // https://github.com/gotwarlost/istanbul/blob/master/ignoring-code-for-coverage.md#ignoring-code-for-coverage-purposes
      // istanbul ignore else
      if ({}.hasOwnProperty.call(options, i)) {
        array[i] = toString(options[i]);
      }
    }
    return array.indexOf(str) >= 0;
  } else if (typeof options === 'object') {
    return options.hasOwnProperty(str);
  } else if (options && typeof options.indexOf === 'function') {
    return options.indexOf(str) >= 0;
  }
  return false;
}
