// Generates nts-react's table of the HTML entities JSX text decodes, from the
// pinned tsgo's JSX transform (`entities` in jsxtransforms/jsx.go), so the
// lowering decodes exactly what TypeScript's `--jsx react-jsx` emit does.
// `--check` fails if the committed table no longer matches.
//
// usage: node tools/gen-jsx-entities.ts [--check]

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const lane = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(lane, "../../third_party/typescript-go/internal/transformers/jsxtransforms/jsx.go");
const outPath = join(lane, "compiler/nts-react/src/jsx_text/entities.rs");

const go = readFileSync(source, "utf8");
const start = go.indexOf("var entities = map[string]rune{");
const end = go.indexOf("\n}", start);
if (start < 0 || end < 0) throw new Error("jsx.go has no `entities` map any more");
const entries = [...go.slice(start, end).matchAll(/"([A-Za-z0-9]+)":\s*(0x[0-9A-Fa-f]+)/g)].map(([, name, code]) => [name!, code!] as const);
if (entries.length < 200) throw new Error(`only ${entries.length} entities: the map's shape changed`);
entries.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));

const text = `// Generated by runtime/react/tools/gen-jsx-entities.ts from the pinned
// tsgo's JSX transform. Do not edit; rerun the generator after moving the pin.

/// The character a named HTML entity (\`amp\`, \`nbsp\`) stands for.
#[must_use]
pub(super) fn named(name: &str) -> Option<char> {
    ENTITIES
        .binary_search_by_key(&name, |(known, _)| known)
        .ok()
        .and_then(|at| char::from_u32(ENTITIES[at].1))
}

/// Sorted by name.
static ENTITIES: &[(&str, u32)] = &[
${entries.map(([name, code]) => `    ("${name}", ${code}),`).join("\n")}
];
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(outPath, "utf8");
  } catch {
    // Missing counts as stale.
  }
  if (current !== text) {
    console.error(`${outPath} is stale: rerun node tools/gen-jsx-entities.ts`);
    process.exit(1);
  }
} else {
  writeFileSync(outPath, text);
  console.log(`wrote ${outPath} (${entries.length} entities)`);
}
