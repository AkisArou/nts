const inputs = new Map<string, string>();
for (const source of SOURCES) {
  let bytes: Uint8Array;
  if (dataDir !== undefined) bytes = readFileSync(join(dataDir, source.name));
  else {
    const response = await fetch(`https://www.unicode.org/Public/17.0.0/ucd/${source.name}`);
    if (!response.ok) throw new Error(`${source.name}: HTTP ${response.status}`);
    bytes = new Uint8Array(await response.arrayBuffer());
  }
  const sha = createHash("sha256").update(bytes).digest("hex");
  if (sha !== source.sha) throw new Error(`${source.name}: SHA256 ${sha} differs from pin`);
  inputs.set(source.name, new TextDecoder().decode(bytes));
}
function source(name: string): string {
  const text = inputs.get(name);
  if (text === undefined) throw new Error(`Missing ${name}`);
  return text;
}
function hex(cp: number): string { return cp.toString(16).toUpperCase().padStart(4, "0"); }
function literal(text: string): string {
  let escaped = '"';
  for (let i = 0; i < text.length; i++) escaped += "\\u" + hex(text.charCodeAt(i));
  return escaped + '"';
}
function fromHex(text: string): string {
  return text.trim().split(/\s+/).filter(Boolean).map(cp => String.fromCodePoint(parseInt(cp, 16))).join("");
}
function range(text: string): [number, number] {
  const [first, last] = text.trim().split("..");
  if (first === undefined || !/^[0-9A-F]+$/.test(first)) throw new Error(`Invalid range ${text}`);
  return [parseInt(first, 16), parseInt(last ?? first, 16)];
}
const files = new Map<string, string>();
function add(name: string, description: string, tags: string[], body: string, data = ""): void {
  const path = `case-mapping-${name}.ts`;
  if (files.has(path)) throw new Error(`Duplicate case ${path}`);
  files.set(path, `/*---\ndescription: ${description}\nfeatures: [ts-unicode-case-mapping, ts-strings, ${tags.join(", ")}]\n---*/\n` +
    "// Generated by tooling/unicode-cases/case-mapping.ts; Node 24.20.0 / Unicode 17.0 / ICU 78.3.\n" +
    "// Contract: docs/foundations/unicode.md, Staying identical to node.\n" + data + body + "\n");
}
function notice(name: string): string {
  // Preserve the upstream copyright/version/licence header for the derived rows.
  return source(name).split("\n").slice(0, 8).map(line => "// " + line).join("\n") +
    `\n// Source: https://www.unicode.org/Public/17.0.0/ucd/${name}\n`;
}

// FNV-1a over the concatenation of each mapped string's UTF-16 code units.
// Start a fresh hash for each 4096-code-point block, including surrogate code points.
for (const method of ["toLowerCase", "toUpperCase"]) {
  for (let plane = 0; plane < 17; plane++) {
    const start = plane * 0x10000;
    const hashes: [number, number][] = [];
    for (let block = start; block < start + 0x10000; block += 4096) {
      let hash = 0x811c9dc5;
      for (let cp = block; cp < block + 4096; cp++) {
        const input = String.fromCodePoint(cp);
        const output = method === "toLowerCase" ? input.toLowerCase() : input.toUpperCase();
        for (let unit = 0; unit < output.length; unit++) {
          hash = Math.imul(hash ^ output.charCodeAt(unit), 0x01000193) >>> 0;
        }
      }
      hashes.push([block, hash]);
    }
    add(`${method === "toLowerCase" ? "lower" : "upper"}-plane-${plane.toString(16).padStart(2, "0")}`,
      `${method} of every code point U+${hex(start)} through U+${hex(start + 0xffff)} matches Node by 4096-point block.`,
      ["ts-unicode-exhaustive", "ts-arrays", "ts-tuples", "ts-iteration", "ts-numbers"],
      "// Hash: FNV-1a, UTF-16 code units, offset 0x811c9dc5, prime 0x01000193.\n" +
      "// String.fromCodePoint keeps U+D800..U+DFFF as individual lone surrogate code units.\n" +
      "const blocks: [number, number][] = [\n" + hashes.map(([cp, hash]) => `  [0x${hex(cp)}, 0x${hex(hash)}],`).join("\n") + "\n];\n" +
      "for (const [start, expected] of blocks) {\n  let hash = 0x811c9dc5;\n" +
      "  for (let cp = start; cp < start + 4096; cp++) {\n" +
      `    const output = String.fromCodePoint(cp).${method}();\n` +
      "    for (let unit = 0; unit < output.length; unit++) {\n" +
      "      hash = Math.imul(hash ^ output.charCodeAt(unit), 0x01000193) >>> 0;\n    }\n  }\n" +
      `  assert.sameValue(hash, expected, "${method} block U+" + start.toString(16) + "..U+" + (start + 4095).toString(16));\n}`);
  }
}

function examples(name: string, description: string, texts: string[], provenance = ""): void {
  const rows = texts.map(input => `  [${literal(input)}, ${literal(input.toLowerCase())}, ${literal(input.toUpperCase())}],`);
  add(name, description, ["ts-unicode-sequences", "ts-arrays", "ts-tuples", "ts-iteration"],
    "const examples: [string, string, string][] = [\n" + rows.join("\n") + "\n];\n" +
    "for (const [input, lower, upper] of examples) {\n" +
    "  const lowered = input.toLowerCase();\n  const uppered = input.toUpperCase();\n" +
    "  assert.sameValue(lowered, lower, \"lowercase text\");\n  assert.sameValue(lowered.length, lower.length, \"lowercase UTF-16 length\");\n" +
    "  assert.sameValue(uppered, upper, \"uppercase text\");\n  assert.sameValue(uppered.length, upper.length, \"uppercase UTF-16 length\");\n}", provenance);
}

let expansions = 0;
for (const [index, line] of source("SpecialCasing.txt").split("\n").entries()) {
  const data = line.split("#")[0].trim();
  if (data === "") continue;
  const [code, lower, , upper, condition] = data.split(";").map(field => field.trim());
  if (code === undefined || lower === undefined || upper === undefined || condition === undefined) throw new Error("Malformed SpecialCasing row");
  if (condition !== "" || (lower.split(/\s+/).length < 2 && upper.split(/\s+/).length < 2)) continue;
  const input = fromHex(code);
  if (input.toLowerCase() !== fromHex(lower) || input.toUpperCase() !== fromHex(upper)) {
    throw new Error(`Node disagrees with SpecialCasing.txt line ${index + 1}`);
  }
  examples(`expansion-${code.toLowerCase()}`, `The unconditional SpecialCasing expansion for U+${code} preserves exact text and length.`,
    [input], notice("SpecialCasing.txt") + `// SpecialCasing.txt line ${index + 1}: ${data}\n`);
  expansions++;
}
if (expansions !== 103) throw new Error(`Expected 103 unconditional expansion rows, found ${expansions}`);

