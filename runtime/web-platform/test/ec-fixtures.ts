function jwk(curve: CryptoNamedCurve, key: EcHexKey): EcFixturePrivateJwk {
  return {
    kty: "EC", crv: curve,
    x: Buffer.from(key.x, "hex").toString("base64url"),
    y: Buffer.from(key.y, "hex").toString("base64url"),
    d: Buffer.from(key.d, "hex").toString("base64url"),
  };
}

export function ecPrivateJwk(curve: CryptoNamedCurve = "P-256"): EcFixturePrivateJwk {
  return jwk(curve, fixtures[curve]);
}

export function ecPublicJwk(curve: CryptoNamedCurve = "P-256"): EcFixturePublicJwk {
  const { kty, crv, x, y } = ecPrivateJwk(curve);
  return { kty, crv, x, y };
}

export function ecSpki(curve: CryptoNamedCurve = "P-256"): Uint8Array {
  return new Uint8Array(Buffer.from(fixtures[curve].spki, "base64"));
}

export function ecPkcs8(curve: CryptoNamedCurve = "P-256"): Uint8Array {
  return new Uint8Array(Buffer.from(fixtures[curve].pkcs8, "base64"));
}

export function ecRawPublic(curve: CryptoNamedCurve = "P-256"): Uint8Array {
  return new Uint8Array(Buffer.from("04" + fixtures[curve].x + fixtures[curve].y, "hex"));
}

export function ecOrder(curve: CryptoNamedCurve = "P-256"): Uint8Array {
  return new Uint8Array(Buffer.from(fixtures[curve].order, "hex"));
}

export function ecdsaMessage(): Uint8Array {
  return new Uint8Array([0x73, 0x61, 0x6d, 0x70, 0x6c, 0x65]);
}

export function ecdsaSignature(curve: CryptoNamedCurve = "P-256", hash: CryptoDigestName = "SHA-256"): Uint8Array {
  return new Uint8Array(Buffer.from(fixtures[curve].signatures[hash], "hex"));
}

export function ecdhPrivateJwk(curve: CryptoNamedCurve, side: "initiator" | "responder"): EcFixturePrivateJwk {
  return jwk(curve, fixtures[curve][side]);
}

export function ecdhPublicJwk(curve: CryptoNamedCurve, side: "initiator" | "responder"): EcFixturePublicJwk {
  const { kty, crv, x, y } = ecdhPrivateJwk(curve, side);
  return { kty, crv, x, y };
}

export function ecdhSecret(curve: CryptoNamedCurve): Uint8Array {
  return new Uint8Array(Buffer.from(fixtures[curve].secret, "hex"));
}
