// Generate locale-sensitive casing expectations using Node, never nts tables.
// Run from any directory with the Node version pinned in .tool-versions:
//   node tooling/unicode-cases/locale-case.ts
//   node tooling/unicode-cases/locale-case.ts --check
// Use --output-dir=/path/to/empty-directory to review a newly generated set.
// Existing differing cases are never overwritten. There is no network input:
// the complete code-point sweeps and contextual inputs below are the source.
// All expectations and locale-list observations are evaluated with pinned Node.

