int main(void) {
  unsigned failures = 0;
  unsigned count = sizeof rows / sizeof rows[0];
  for (unsigned at = 0; at < count; at++) {
    const Row *row = &rows[at];
    NtsString *s = nts_string_from_utf8((const char *)row->bytes, row->length);
    int same = s->length == row->units;
    for (unsigned unit = 0; same && unit < row->units; unit++) {
      same = nts_unit(s, unit) == row->expected[unit];
    }
    if (!same) {
      failures++;
      printf("row %u:", at);
      for (unsigned b = 0; b < row->length; b++) {
        printf(" %02X", row->bytes[b]);
      }
      printf(" -> got");
      for (uint32_t unit = 0; unit < s->length; unit++) {
        printf(" %04X", (unsigned)nts_unit(s, unit));
      }
      printf(", node gives");
      for (unsigned unit = 0; unit < row->units; unit++) {
        printf(" %04X", row->expected[unit]);
      }
      printf("\n");
    }
  }
  printf("utf8: %u of %u rows agree with TextDecoder\n", count - failures,
         count);
  return failures == 0 ? 0 : 1;
}

