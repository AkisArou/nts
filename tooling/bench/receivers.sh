#!/usr/bin/env bash
# Field accesses per benchmark case, by what the receiver is typed as.
#
# A cost paid on every field read is a benchmark question before it is a corpus
# question, and `nts receivers` takes a `tsconfig.json` like every other
# subcommand. A bench case has none: `benches/tsconfig.json` explains why --
# "compiling fifty cases as one program would make every export a root of every
# other" -- so `tooling/bench` generates one per case at run time and this
# reproduces that generation rather than inventing a second shape for it. Keep it
# in step with `case_tsconfig` in `tooling/bench/src/main.rs`.
#
# Written into `target/` for the same reason bench does: the cases keep no
# generated files.
set -euo pipefail

root="$(cd "$(dirname "$0")/../.." && pwd)"
nts="${NTS_BIN:-$root/target/release/nts}"
out="$root/target/bench-receivers"
mkdir -p "$out"

[ -x "$nts" ] || { echo "no nts at $nts (set NTS_BIN)" >&2; exit 1; }

printf '%-28s %8s %10s %9s\n' case accesses interface share
for case_dir in "$root"/benches/cases/*/; do
  name="$(basename "$case_dir")"
  config="$case_dir/tsconfig.json"
  if [ ! -f "$config" ]; then
    config="$out/$name.tsconfig.json"
    cat > "$config" <<JSON
{
  "//": "Generated by tooling/bench/receivers.sh, mirroring bench's case_tsconfig.",
  "extends": "$root/tsconfig.fixtures.json",
  "include": ["${case_dir%/}"]
}
JSON
  fi
  line="$("$nts" receivers "$config" 2>/dev/null | grep '^broad indirection costs' || true)"
  if [ -z "$line" ]; then
    # Either nothing reaches an interface, or the case did not produce a
    # snapshot. The two are different answers and neither is a share.
    if "$nts" receivers "$config" 2>/dev/null | grep -q 'no field access in this program reaches'; then
      total="$("$nts" receivers "$config" 2>/dev/null | awk '/^total,/ {print $(NF-1)}')"
      printf '%-28s %8s %10s %9s\n' "$name" "${total:-0}" 0 "0.0%"
    else
      printf '%-28s %8s %10s %9s\n' "$name" "-" "-" "no snapshot"
    fi
    continue
  fi
  # "broad indirection costs N of M field accesses (P%)."
  n="$(echo "$line" | awk '{print $4}')"
  m="$(echo "$line" | awk '{print $6}')"
  p="$(echo "$line" | sed 's/.*(\(.*\))\./\1/')"
  printf '%-28s %8s %10s %9s\n' "$name" "$m" "$n" "$p"
done
