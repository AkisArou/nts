// Generate the closed native internal-name inventory, never underscore decoding.
// node compiler/frontend-tsrs/names.ts [--check] [--vendor <root>] [--out <adapter>]
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
const adapter = dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const flag = (name: string) => { const i = args.indexOf(name); return i < 0 ? undefined : args[i + 1]; };
for (let i = 0; i < args.length; i++) {
  if (["--vendor", "--out"].includes(args[i]) && args[i + 1]) i++;
  else if (args[i] !== "--check") throw new Error(`unknown names argument: ${args[i]}`);
}
const vendor = resolve(flag("--vendor") ?? join(adapter, "../../third_party/tsrs"));
const out = resolve(flag("--out") ?? adapter);
const source = readFileSync(join(vendor, "crates/tsrs_ast/src/symbol.rs"), "utf8");
const table = [...source.matchAll(/^pub const (INTERNAL_SYMBOL_NAME_(\w+)): &str = "([^"]*)";/gm)]
  .filter((entry) => entry[2] !== "PREFIX")
  .map(([, constant, suffix, value]) => ({ constant, variant: suffix === "JSX_ATTRIBUTES" ? "JSXAttributes" : suffix.toLowerCase().split("_").map((s) => s[0].toUpperCase() + s.slice(1)).join(""), value }));
if (!table.length || table.some((entry) => !entry.value)) throw new Error("no recognized native internal-name table");
const declarations = [...source.matchAll(/^pub const INTERNAL_SYMBOL_NAME_(?!PREFIX)\w+: &str/gm)];
if (declarations.length !== table.length) throw new Error("unknown native internal-name declaration form");
let rust = "// Generated by names.ts from tsrs_ast/src/symbol.rs. Do not edit.\nuse crate::JsString;\n#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]\npub enum InternalName<'p> {\n";
for (const entry of table) rust += `${entry.variant},\n`;
rust += "/// An unrecognized native DEL name, retained for a named refusal.\nOther(JsString<'p>),\n}\n\npub(super) fn internal_name<'p>(name: &str) -> Option<InternalName<'p>> {\nSome(match name {\n";
for (const entry of table) rust += `tsrs_ast::${entry.constant} => InternalName::${entry.variant},\n`;
rust += "_ => return None,\n})\n}\n";
rust = execFileSync("rustfmt", ["--edition", "2024", "--config-path", join(adapter, "../../rustfmt.toml"), "--emit", "stdout"], { input: rust }).toString();
const files = [["src/internal_names.rs", rust], ["api/internal-names.json", JSON.stringify(table, null, 2) + "\n"]];
if (args.includes("--check")) {
  const scratch = mkdtempSync(join(process.env.TMPDIR ?? join(process.env.HOME!, ".cache"), "nts-tsrs-names-"));
  try {
    const changed: string[] = [];
    for (const [name, contents] of files) {
      const actual = join(out, name), expected = join(scratch, name);
      mkdirSync(dirname(expected), { recursive: true }); writeFileSync(expected, contents);
      if (readFileSync(actual, "utf8") !== contents) {
        changed.push(name);
        try { execFileSync("diff", ["-u", actual, expected], { stdio: "inherit" }); } catch {}
      }
    }
    if (changed.length) throw new Error(`native internal-name drift: ${changed.join(", ")}; run node compiler/frontend-tsrs/names.ts`);
  } finally { rmSync(scratch, { recursive: true, force: true }); }
} else for (const [name, contents] of files) { mkdirSync(dirname(join(out, name)), { recursive: true }); writeFileSync(join(out, name), contents); }
process.stdout.write(`native internal names: ${table.length} constants verified\n`);
