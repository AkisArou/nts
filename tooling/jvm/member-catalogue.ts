// One implementation renders and verifies the JVM member catalogue.
import assert from "node:assert/strict";
import {readFileSync, writeFileSync, mkdirSync} from "node:fs";
import {dirname, resolve} from "node:path";
import {spawnSync} from "node:child_process";
import {gitArguments} from "../gate/git-arguments/main.ts";
import {checkGrammar, withoutRecordedMethods} from "./member-grammar.ts";

type Role = {rust: string; stem: string; key: "none" | "name"; suffix?: string};
type Catalogue = {
  version: number;
  prefix: string;
  observer: {legacy_raising_suffix: string};
  name_escape: {ascii_literal: string; escaped_non_ascii: number[]};
  roles: Role[];
  java_templates: {template: string; output: string}[];
};

const catalogue = "compiler/codegen/jvm/member-names.json";
const rustOutput = "compiler/codegen/jvm/src/generated_members.rs";
const bindingsOutput = "compiler/codegen/jvm/generated-members.json";
export function catalogueFiles(root:string):string[]{
  const model:Catalogue=JSON.parse(readFileSync(resolve(root,catalogue),'utf8'));
  return [catalogue,rustOutput,bindingsOutput,'runtime/jvm/nts-runtime.jar',
    ...model.java_templates.flatMap(row=>[row.template,row.output])];
}

export function runMemberCatalogue(options:{root:string;check:boolean;directories:readonly string[];
  report?:(line:string)=>void;error?:(line:string)=>void}):number{
const {root,check,directories}=options,report=options.report??console.log,error=options.error??console.error;
assert(directories.length>0&&directories.every(path=>/^[A-Za-z0-9_.-]+(?:\/[A-Za-z0-9_.-]+)*$/.test(path)
  &&path.split('/').every(part=>part!=='.'&&part!=='..')),'invalid member audit directory');
const model:Catalogue=JSON.parse(readFileSync(resolve(root,catalogue),'utf8'));
assert.equal(model.version, 1);
checkGrammar(model);
assert(!/^[$_\p{ID_Start}][$_\u200c\u200d\p{ID_Continue}]*$/u.test(model.prefix),
  "the reserved prefix must be outside authored identifier syntax");
const fullName = (role: Role) => model.prefix + role.stem;
const roleIdentity = (role: Role) => fullName(role) + ":" + (role.suffix ?? "");
const seenNames = new Set();
const seenRust = new Set();
for (const role of model.roles) {
  assert(["none", "name"].includes(role.key));
  assert(role.suffix === undefined || /^[A-Za-z][A-Za-z0-9]*$/.test(role.suffix));
  assert(/^[A-Za-z_][A-Za-z_0-9]*$/.test(role.rust));
  assert(/^[A-Za-z][A-Za-z0-9]*$/.test(role.stem));
  assert(!seenRust.has(role.rust) && !seenNames.has(roleIdentity(role)));
  seenRust.add(role.rust);
  seenNames.add(roleIdentity(role));
  assert(!/[.;[/<>]/.test(fullName(role)), "invalid JVM member name");
}

const fixed = new Map(model.roles.filter(role => role.key === "none")
  .map(role => [role.rust, fullName(role)]));
const javaTokens = new Map(fixed);
javaTokens.set("PREFIX", model.prefix);
javaTokens.set("LEGACY_RAISING_SUFFIX", model.observer.legacy_raising_suffix);
const quote = (text: string) => JSON.stringify(text);
const rust = [
  "//! Generated by generate-members.ts from member-names.json. Do not edit.",
  "",
  `pub const PREFIX: &str = ${quote(model.prefix)};`,
  `pub const LEGACY_RAISING_SUFFIX: &str = ${quote(model.observer.legacy_raising_suffix)};`,
];
for (const role of model.roles) {
  const name = fullName(role);
  if (role.key === "none") {
    rust.push(`pub const ${role.rust}: &str = ${quote(name)};`);
  } else {
    const stem = role.rust.toUpperCase() + "_PREFIX";
    rust.push(`pub const ${stem}: &str = ${quote(name + "$")};`);
    rust.push("", "#[must_use]");
    rust.push(`pub fn ${role.rust}(key: &str) -> String {`);
    if (role.suffix) {
      rust.push(`    let mut name = readable_name(${stem}, key);`,
        `    name.push_str(${quote("$" + role.suffix)});`, "    name");
    } else rust.push(`    readable_name(${stem}, key)`);
    rust.push("}");
  }
}
rust.push("", "/// The catalogue's injective, readable escape for a source identity.",
  "#[must_use]", "pub fn escaped_name(key: &str) -> String {", '    readable_name("", key)', "}",
  "", "fn readable_name(prefix: &str, key: &str) -> String {",
  "    use std::fmt::Write as _;",
  `    const ASCII: &str = ${quote(model.name_escape.ascii_literal)};`,
  `    const ESCAPED: &[u32] = &[${model.name_escape.escaped_non_ascii.join(", ")}];`,
  "    let mut name = String::with_capacity(prefix.len() + key.len());",
  "    name.push_str(prefix);",
  "    for ch in key.chars() {",
  "        let literal = if ch.is_ascii() { ASCII.contains(ch) } else { !ESCAPED.contains(&u32::from(ch)) };",
  "        if literal {",
  "            name.push(ch);",
  "        } else {",
  '            assert!(write!(name, "${:x}$", u32::from(ch)).is_ok());',
  "        }",
  "    }", "    name", "}");
rust.push("", "pub const SPECIMENS: &[&str] = &[");
for (const role of model.roles) {
  const suffix = role.key === "none" ? "" : "$sample" + (role.suffix ? "$" + role.suffix : "");
  rust.push(`    ${quote(fullName(role) + suffix)},`);
}
rust.push("];");
rust.push("", "pub const JAVA_TOKENS: &[(&str, &str)] = &[");
for (const role of javaTokens.keys()) {
  rust.push(`    (${quote("@@" + role + "@@")}, ${role}),`);
}
rust.push("];");

const formattedRust = spawnSync("rustfmt", ["--edition", "2024", "--emit", "stdout"], {
  cwd: root, input: rust.join("\n") + "\n", encoding: "utf8",
});
assert.equal(formattedRust.status, 0, formattedRust.error?.message ?? formattedRust.stderr);
const outputs = new Map([
  [rustOutput, formattedRust.stdout],
  [bindingsOutput, JSON.stringify({version: 1, fixed: Object.fromEntries(fixed)}, null, 2) + "\n"],
]);
for (const template of model.java_templates) {
  const input = readFileSync(resolve(root, template.template), "utf8");
  const body = input.replace(/@@([A-Z_]+)@@/g, (_, role) => {
    const name = javaTokens.get(role);
    assert(name !== undefined, `unknown role ${role} in ${template.template}`);
    return name;
  });
  assert(!/@@[A-Z_]+@@/.test(body));
  assert(!outputs.has(template.output));
  outputs.set(template.output,
    "// Generated from a member-templates source by generate-members.ts. Do not edit.\n" + body);
}
let bad = false;
for (const [path, expected] of outputs) {
  const actual = resolve(root, path);
  if (check) {
    if (readFileSync(actual, "utf8") !== expected) {
      error(`generated JVM member source is stale: ${path}`);
      bad = true;
    }
  } else {
    mkdirSync(dirname(actual), {recursive: true});
    writeFileSync(actual, expected);
  }
}

// Test untracked source too: a new protocol cannot acquire a second literal
// merely because its file has not been staged yet. Generated outputs must
// additionally pass the exact byte comparison above.
if (check) {
  const listed = spawnSync("git", gitArguments(["ls-files", "-z", "--cached", "--others",
    "--exclude-standard", "--", ...directories]), {cwd: root, encoding: "utf8"});
  assert.equal(listed.status, 0, listed.stderr);
  const allowed = new Set([catalogue, ...outputs.keys()]);
  for (const path of new Set(listed.stdout.split("\0").filter(Boolean))) {
    if (allowed.has(path)) continue;
    const bytes = readFileSync(resolve(root, path));
    // This declared build artifact contains compressed class bytes. A NUL in
    // any source or unknown data file is not evidence that it is an artifact.
    if (path === "runtime/jvm/nts-runtime.jar") {
      assert(bytes.subarray(0, 4).equals(Buffer.from([0x50, 0x4b, 0x03, 0x04])),
        `declared JVM runtime artifact is not a ZIP archive: ${path}`);
      continue;
    }
    let text = bytes.toString("utf8").replace(/\\u\{([0-9a-f]+)\}|\\u([0-9a-f]{4})/gi,
      (literal, rustHex, javaHex) => {
        const hex:string|undefined=rustHex??javaHex;assert(hex!==undefined);
        const point = parseInt(hex, 16);
        // Source fixtures can deliberately spell invalid Unicode escapes.
        return point <= 0x10ffff ? String.fromCodePoint(point) : literal;
      });
    if (path === "tooling/conformance/jvm-verifies.known") text = withoutRecordedMethods(model, text);
    if (text.includes(model.prefix)) {
      error(`reserved JVM member prefix outside its catalogue/generated outputs: ${path}`);
      bad = true;
    }
  }
}
if (!bad) report(`${check ? "checked" : "generated"} ${outputs.size} JVM member sources`);
return bad?1:0;
}
