//! What a `nts bind-gir` request adds to a namespace beyond its GIR: a header
//! GIR's `<c:include>` does not reach, and the macro it needs, carried to
//! every place the header is included -- the binder's probes and self-check,
//! and the compiled program, as `@ntsDefine` before `@ntsHeader`'s include.
//!
//! `gio/gsettingsbackend.h` is the case: it declares
//! `g_settings_backend_get_default`, which `Gio-2.0.gir` describes, and
//! refuses to be included unless `G_SETTINGS_ENABLE_BACKEND` is defined.

#![cfg(target_os = "linux")]
#![allow(clippy::unwrap_used, clippy::expect_used)]

use std::path::{Path, PathBuf};
use std::process::Command;

fn scratch(name: &str) -> PathBuf {
    let dir = Path::new(env!("CARGO_TARGET_TMPDIR"))
        .join(format!("bind-gir-request-{name}-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).expect("scratch directory");
    dir
}

fn gio_flags() -> Option<Vec<String>> {
    let output = Command::new("pkg-config")
        .args(["--cflags", "gio-2.0"])
        .output()
        .ok()?;
    output.status.success().then(|| {
        String::from_utf8_lossy(&output.stdout)
            .split_whitespace()
            .map(str::to_owned)
            .collect()
    })
}

fn bind(out: &Path, request: &[&str]) -> std::process::Output {
    Command::new(env!("CARGO_BIN_EXE_nts"))
        .args(["bind-gir", "Gio-2.0", "--out"])
        .arg(out)
        .args(request)
        .output()
        .expect("running nts bind-gir")
}

/// A program calling `g_settings_backend_get_default` through the bindings
/// in `dir/bindings`, emitted by `nts emit-c` into `dir/c` with nothing
/// refused.
fn emit_caller(dir: &Path) {
    let repo = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .canonicalize()
        .unwrap();
    std::fs::write(
        dir.join("main.ts"),
        "import { g_settings_backend_get_default } from \"c:Gio-2.0\";\n\
         export function backend(): boolean {\n  return g_settings_backend_get_default() !== null;\n}\n",
    )
    .unwrap();
    let mut files = vec!["main.ts".to_owned()];
    for entry in std::fs::read_dir(dir.join("bindings")).unwrap() {
        let name = entry.unwrap().file_name().into_string().unwrap();
        if name.ends_with(".d.ts") {
            files.push(format!("bindings/{name}"));
        }
    }
    files.push(repo.join("runtime/native/libc.d.ts").display().to_string());
    std::fs::write(
        dir.join("tsconfig.json"),
        serde_json::json!({ "extends": repo.join("tsconfig.fixtures.json"), "files": files })
            .to_string(),
    )
    .unwrap();
    let emitted = Command::new(env!("CARGO_BIN_EXE_nts"))
        .arg("emit-c")
        .arg(dir.join("tsconfig.json"))
        .arg("--out")
        .arg(dir.join("c"))
        .output()
        .expect("running nts emit-c");
    let said = String::from_utf8_lossy(&emitted.stderr);
    assert!(emitted.status.success() && !said.contains("NTS"), "{said}");
}

const REQUEST: [&str; 6] = [
    "--package",
    "Gio-2.0:gio-unix-2.0",
    "--define",
    "Gio-2.0:G_SETTINGS_ENABLE_BACKEND",
    "--header",
    "Gio-2.0:gio/gsettingsbackend.h",
];

#[test]
fn a_requested_header_and_its_macro_reach_the_compiled_program() {
    let Some(flags) = gio_flags() else {
        eprintln!("skipping: no gio-2.0 pkg-config entry");
        return;
    };
    if !Path::new("/usr/share/gir-1.0/Gio-2.0.gir").exists() {
        eprintln!("skipping: no Gio-2.0.gir");
        return;
    }
    let dir = scratch("reach");

    // The control: GIR's headers alone do not declare it.
    let plain = bind(&dir.join("plain"), &[]);
    assert!(
        plain.status.success(),
        "{}",
        String::from_utf8_lossy(&plain.stderr)
    );
    let refused = std::fs::read_to_string(dir.join("plain/Gio-2.0.refused.txt")).unwrap();
    assert!(
        refused.lines().any(|line| line
            == "g_settings_backend_get_default\tdeclared by none of the headers GIR names"),
        "{refused}"
    );

    let bound = bind(&dir.join("bindings"), &REQUEST);
    assert!(
        bound.status.success(),
        "{}",
        String::from_utf8_lossy(&bound.stderr)
    );
    let gio = std::fs::read_to_string(dir.join("bindings/Gio-2.0.d.ts")).unwrap();
    assert!(gio.starts_with(
        "// Generated by `nts bind-gir Gio-2.0 --package Gio-2.0:gio-unix-2.0 --define Gio-2.0:G_SETTINGS_ENABLE_BACKEND --header Gio-2.0:gio/gsettingsbackend.h`."
    ));
    // GIR's package and the request's, which a program using the module
    // compiles and links against.
    assert!(
        gio.contains(" * @ntsPackage gio-2.0 gio-unix-2.0\n"),
        "{gio}"
    );
    assert!(
        gio.contains(" * @ntsHeader gio/gsettingsbackend.h\n"),
        "{gio}"
    );
    assert!(
        gio.contains(" * @ntsDefine G_SETTINGS_ENABLE_BACKEND\n"),
        "{gio}"
    );
    assert!(gio.contains("export function g_settings_backend_get_default("));

    // A caller, emitted and compiled: the program and the compiler's own
    // witness of the declaration, which includes the header under the macro.
    emit_caller(&dir);
    let witness = std::fs::read_to_string(dir.join("c/native_witness.c")).unwrap();
    let define = witness
        .find("#define G_SETTINGS_ENABLE_BACKEND 1")
        .expect("the macro in the witness");
    let include = witness
        .find("#include <gio/gsettingsbackend.h>")
        .expect("the header in the witness");
    assert!(define < include, "{witness}");
    let compile = |file: &Path| {
        Command::new("clang")
            .args(["-std=c11", "-fsyntax-only", "-w"])
            .arg(format!("-I{}", dir.join("c").display()))
            .args(&flags)
            .arg(file)
            .output()
            .expect("running clang")
    };
    for file in ["program.c", "native_witness.c"] {
        let compiled = compile(&dir.join("c").join(file));
        assert!(
            compiled.status.success(),
            "{file}: {}",
            String::from_utf8_lossy(&compiled.stderr)
        );
    }
    // One difference: the same witness without the macro does not compile.
    let without = dir.join("c/witness-without-macro.c");
    std::fs::write(
        &without,
        witness.replace("#define G_SETTINGS_ENABLE_BACKEND 1\n", ""),
    )
    .unwrap();
    assert!(!compile(&without).status.success());
    std::fs::remove_dir_all(dir).unwrap();
}

/// A request is checked: a header that does not compile under its
/// namespace's flags and macros -- `gsettingsbackend.h` without its macro --
/// and a namespace outside the closure are errors that name them.
#[test]
fn a_request_is_checked_before_anything_is_bound() {
    if gio_flags().is_none() || !Path::new("/usr/share/gir-1.0/Gio-2.0.gir").exists() {
        eprintln!("skipping: no gio-2.0");
        return;
    }
    let dir = scratch("checked");
    let unguarded = bind(
        &dir.join("a"),
        &["--header", "Gio-2.0:gio/gsettingsbackend.h"],
    );
    let said = String::from_utf8_lossy(&unguarded.stderr);
    assert!(!unguarded.status.success());
    assert!(
        said.contains(
            "`--header Gio-2.0:gio/gsettingsbackend.h` does not compile under Gio-2.0's flags"
        ),
        "{said}"
    );
    let outside = bind(&dir.join("b"), &["--header", "Gtk-4.0:gtk/gtk.h"]);
    let said = String::from_utf8_lossy(&outside.stderr);
    assert!(!outside.status.success());
    assert!(
        said.contains("the bind request names `Gtk-4.0`, which is not in Gio-2.0's closure"),
        "{said}"
    );
    let unnamed = bind(&dir.join("c"), &["--header", "gio/gsettingsbackend.h"]);
    assert!(!unnamed.status.success());
    assert!(String::from_utf8_lossy(&unnamed.stderr).contains("names no namespace"));
    // A header GIR already names declares nothing new: bound, and said so.
    let idle = bind(&dir.join("d"), &["--header", "Gio-2.0:gio/gio.h"]);
    assert!(idle.status.success());
    assert!(
        String::from_utf8_lossy(&idle.stderr)
            .contains("the requested headers declare none of Gio-2.0's callables its own do not"),
        "{}",
        String::from_utf8_lossy(&idle.stderr)
    );
    std::fs::remove_dir_all(dir).unwrap();
}
