#[must_use]
pub fn to_semantic(native_kind: u16) -> Option<u16> {
    KINDS.get(usize::from(native_kind)).map(|entry| entry.1)
}

#[cfg(test)]
#[path = "native_role_tests.rs"]
mod role_tests;

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_native_kind_inventory_matches_by_count_and_name() {
        let path = std::env::var_os("NTS_TEST_TSRS_KIND_FILE").map_or_else(
            || {
                std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
                    .join("../../third_party/tsrs/crates/tsrs_ast/src/kind.rs")
            },
            std::path::PathBuf::from,
        );
        let source = std::fs::read_to_string(path).expect("pinned tsrs kind inventory");
        let body = source
            .split_once("pub enum Kind {")
            .expect("native Kind enum")
            .1
            .split_once("\n}")
            .expect("enum end")
            .0;
        let actual: Vec<_> = body
            .lines()
            .filter_map(|line| {
                let name = line.split("//").next()?.trim().strip_suffix(',')?;
                (!name.is_empty() && name.bytes().all(|c| c.is_ascii_alphanumeric() || c == b'_'))
                    .then_some(name)
            })
            .collect();
        assert_eq!(
            actual.len(),
            KINDS.len(),
            "native syntax kind count changed"
        );
        for (at, (actual, (expected, semantic))) in actual.iter().zip(KINDS).enumerate() {
            assert_eq!(actual, &expected, "native kind {at}");
            assert!(
                syntax::name_of(semantic).is_some(),
                "semantic tag {semantic}"
            );
        }
    }

    #[test]
    fn a_new_native_keyword_does_not_renumber_semantic_nodes() {
        assert_eq!(to_semantic(167), Some(syntax::SOURCE_KEYWORD));
        assert_eq!(to_semantic(168), Some(167));
        assert_eq!(to_semantic(308), Some(syntax::SOURCE_FILE));
        assert_eq!(to_semantic(353), None);
    }
}
