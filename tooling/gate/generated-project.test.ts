const under=(root:string,path:string)=>{const value=relative(root,path);return value!=='..'&&!value.startsWith('../')&&!isAbsolute(value);};
test('generated configs retain exact full-Program repository facts across real private ConfigDirs',t=>{
  const base=testScratch(t,'generated-project-context'),source=join(base,'source');mkdirSync(join(source,'case'),{recursive:true});
  writeFileSync(join(source,'package.json'),'{"name":"generated-project-control","type":"module"}');
  writeFileSync(join(source,'base.json'),' {"compilerOptions":{"module":"esnext","moduleResolution":"bundler","strict":true,"types":[]}}');
  writeFileSync(join(source,'case/main.ts'),"import {value} from './dependency.js';export const answer=value;");writeFileSync(join(source,'case/dependency.ts'),'export const value=1;');
  for(const include of ['directory','typescript-tree'] as const){
    const sourceOwner=projectInputOwner(source,undefined,join(base,'rendered',include)),old=projectInputOwner(base),seen=[];
    try{
      for(const prefix of ['one','different/depth/two']){
        const directory=join(base,prefix,include);mkdirSync(directory,{recursive:true});const config=join(directory,'tsconfig.json');
        const pattern=join(source,'case')+(include==='typescript-tree'?'/**/*.ts':'');
        // These are the two actual generators' JSON structures, with the
        // original options inherited rather than replaced for projection.
        const body=include==='typescript-tree'?`{"extends": "${join(source,'base.json')}", "include": ["${pattern}"]}`:
          `{\n  "//": "Generated by tooling/bench. The case keeps no config of its own.",\n  "extends": "${join(source,'base.json')}",\n  "include": ["${pattern}"]\n}\n`;
        writeFileSync(config,body);
        const original=old.read([{kind:'config',path:relative(base,config)}]),current=sourceOwner.read([{kind:'generated',path:'base.json',directory:'case',include}]);
        const actual=original.observations.filter(row=>under(source,row.path));assert.deepEqual(current.observations,actual,'exact repository callback rows');
        assert.deepEqual(current.roots.map(path=>join(source,path)).sort(),original.roots.map(path=>join(base,path)).sort());
        assert.equal(current.generatedObservations.length,3);assert.ok(current.generatedObservations.every(row=>generatedProjectFact(row.capability,row.observation)));
        assert.ok(current.generatedObservations.every(row=>!existsSync(row.capability.root)),'prepared ConfigDir is disposed after Program completion');seen.push(current.observations);
      }
      assert.deepEqual(seen[0],seen[1]);
    }finally{sourceOwner.close();old.close();}
  }
});
test('generated project graph preserves missing supplied selection and immutable repository closure',t=>{
  const base=testScratch(t,'generated-project-selection'),root=join(base,'source');mkdirSync(join(root,'case'),{recursive:true});
  writeFileSync(join(root,'package.json'),'{"name":"generated-project-control","type":"module"}');
  writeFileSync(join(root,'base.json'),'{"compilerOptions":{"types":[]}}');writeFileSync(join(root,'case/main.ts'),'export const value=1;');writeFileSync(join(root,'case/other.ts'),'export const other=2;');
  const declarations=new Map([['reader.rs',{imports:[],assets:[{kind:'generated-project' as const,path:'./base.json',directory:'./case/',include:'directory' as GeneratedInclude}]}]]);
  writeFileSync(join(root,'reader.rs'),'');
  const describe=()=>{const graph=moduleGraph({sourceRoot:root,declarations,generatedTemporaryParent:join(base,'private')});try{return graph.describe(['reader.rs']);}finally{graph.close();}};
  const generated=describe();assert.ok(generated.files.includes('case/main.ts'));assert.ok(generated.files.includes('case/other.ts'));
  assert.ok(generated.optionalFiles.some(row=>row.path==='case/tsconfig.json'&&!row.present));
  const privateFacts=generated.observations.filter(row=>row.capability?.kind==='generated-project');assert.equal(privateFacts.length,3);
  assert.ok(privateFacts.every(row=>readerObservationDependency(root,row)===undefined));validateReaderSourceObservations(generated,root);
  writeFileSync(join(root,'case/tsconfig.json'),'{"compilerOptions":{"types":[]},"files":["other.ts"]}');
  const supplied=describe();assert.ok(supplied.files.includes('case/other.ts'));assert.ok(!supplied.files.includes('case/main.ts'));
  assert.ok(!supplied.files.includes('base.json'));
  assert.ok(!supplied.observations.some(row=>row.capability?.kind==='generated-project'));
});
test('prepared facts refuse unsupported callbacks, malformed recipes and cleanup after parse failure',t=>{
  const base=testScratch(t,'generated-project-refusal'),source=join(base,'source');mkdirSync(join(source,'case'),{recursive:true});
  writeFileSync(join(source,'base.json'),'{broken');const parent=join(base,'private'),owner=projectInputOwner(source,undefined,parent);
  try{assert.throws(()=>owner.read([{kind:'generated',path:'base.json',directory:'case',include:'directory'}]),/cannot be parsed/);}finally{owner.close();}
  assert.deepEqual(readdirSync(parent),[],'failed parsing disposes its owned generated ConfigDir');
  const prepared=prepareGeneratedProject({source,extends:'base.json',directory:'case',include:'directory',parent});
  try{
    assert.equal(readFileSync(prepared.config,'utf8'),prepared.capability.body);
    assert.equal(generatedProjectFact(prepared.capability,{kind:'stat',path:prepared.capability.root,value:null}),false);
    assert.equal(generatedProjectFact({...prepared.capability,body:'broken'},{kind:'file',path:prepared.config,value:null}),false);
  }finally{prepared.close();}
  assert.throws(()=>prepareGeneratedProject({source,extends:'../outside.json',directory:'case',include:'directory',parent}),/escape/);
});
